async function findItemsCurrentShells(client, ids) {
  const requestedIds = planValidationUnique(ids);
  const result = new Map();
  // Every invocation reads fresh state. A bounded IDs filter fits in one page
  // and avoids an environment-wide scan or ordering-dependent pagination.
  for (let offset = 0; offset < requestedIds.length; offset += 100) {
    const batch = requestedIds.slice(offset, offset + 100);
    if (typeof client.items.rawList === 'function') {
      const response = await client.items.rawList({
        filter: { ids: batch.join(',') },
        version: 'current',
        nested: false,
        page: { offset: 0, limit: 100 },
      });
      if (
        !isObject(response) || !Array.isArray(response.data) || !isObject(response.meta) ||
        !Number.isInteger(response.meta.total_count) || response.meta.total_count < 0 ||
        response.meta.total_count > batch.length || response.data.length !== response.meta.total_count
      ) {
        throw runtimeError('INVALID_CMA_RESPONSE', 'The targeted current item list returned an incomplete or invalid page.');
      }
      const requested = new Set(batch);
      for (const resource of response.data) {
        const model = isObject(resource) && isObject(resource.relationships) &&
          isObject(resource.relationships.item_type) ? resource.relationships.item_type.data : null;
        if (
          !isObject(resource) || resource.type !== 'item' || !requested.has(resource.id) || result.has(resource.id) ||
          !isObject(resource.attributes) || !isObject(model) || model.type !== 'item_type' ||
          typeof model.id !== 'string' || !model.id || !isObject(resource.meta) ||
          ['publication_scheduled_at', 'unpublishing_scheduled_at'].some(function (key) {
            return !Object.prototype.hasOwnProperty.call(resource.meta, key) ||
              (resource.meta[key] !== null && typeof resource.meta[key] !== 'string');
          })
        ) {
          throw runtimeError('INVALID_CMA_RESPONSE', 'The targeted current item list returned an invalid, duplicate, or unrequested record shell.');
        }
        result.set(resource.id, {
          id: resource.id,
          type: resource.type,
          position: resource.attributes.position,
          parent_id: resource.attributes.parent_id,
          item_type: model,
          meta: resource.meta,
        });
      }
    }
    // List omission does not establish absence: permission filtering and Item
    // visibility can differ. Preserve the individual lookup's 404/error rules.
    // Clients without rawList retain those same individual reads throughout.
    const missing = batch.filter(function (id) { return !result.has(id); });
    const resolved = await mapWithConcurrency(missing, 5, async function (id) {
      return [id, await findItemCurrentShellMaybe(client, id)];
    });
    for (const entry of resolved) result.set(entry[0], entry[1]);
  }
  return result;
}

