import { CmaClient } from '@datocms/cli-utils';
import type { Dump } from '../dump/format';
import {
  type RawSchema,
  type SchemaView,
  schemaDifferences,
  schemaView,
} from '../schema';
import { bulletList, userError } from '../utils/errors';

interface SchemaCheck {
  dump: Dump;
  /** The dump's schema view. */
  expected: SchemaView;
  target: string;
  trackingModelApiKey: string;
  /** Reads the schema of an environment of the target's project. */
  readSchema: (environment: string) => Promise<RawSchema>;
}

/**
 * Checks that the target environment has the dump's schema, the only
 * comparison the import makes. On a mismatch, the error lists the
 * differences and says how to give the target the dump's schema.
 */
export async function assertSameSchema(check: SchemaCheck): Promise<void> {
  const { target, trackingModelApiKey } = check;
  const targetSchema = await check.readSchema(target);
  const differences = schemaDifferences(
    check.expected,
    schemaView(targetSchema, trackingModelApiKey),
    target,
  );
  if (!differences.length) return;
  const { message, suggestions } = await mismatchAdvice(
    check,
    targetSchema.site.data.id,
  );
  throw userError(
    'SCHEMA_MISMATCH',
    `Environment "${target}" does not have the schema of the dump, so the dump cannot be imported into it. Differences between the dump and "${target}":\n${bulletList(
      differences,
    )}\n${message}`,
    suggestions,
  );
}

/**
 * How to give the target the dump's schema. The native CLI generates a
 * migration that copies one environment's schema to another of the same
 * project, creating models and fields under the IDs they have there, so the
 * environment the dump was exported from can serve, if it still exists and
 * still has that schema.
 */
async function mismatchAdvice(
  check: SchemaCheck,
  targetSiteId: string,
): Promise<{ message: string; suggestions?: string[] }> {
  const { dump, target, trackingModelApiKey } = check;
  const { site, createdAt } = dump.manifest;
  const source = site.environment;
  const exported = `The dump was exported from environment "${source}"`;
  if (targetSiteId !== site.id)
    return {
      message: `${exported} of another project (${site.id}) on ${createdAt}. The import keeps the dump's model IDs, and migrations generated with "datocms migrations:new --autogenerate" copy a schema only between environments of one project, so import the dump into an empty sandbox environment of the project it was exported from.`,
    };

  const migration = (from: string) => [
    `datocms migrations:new copyDumpSchema --autogenerate=${from}:${target}`,
    `datocms migrations:run --source=${target} --in-place --migrations-dir=<a directory holding only the generated script>`,
  ];
  const howToRun = `The migration commands need a datocms.config.json profile ("datocms link" creates one) and the same --profile or --api-token as this command. Move the generated script out of your migrations directory, so that migrations:run runs it alone and your other environments never do, and if it creates the "${trackingModelApiKey}" model, remove that part, since migrations:run creates that model itself.`;
  const sourceSchema = await check
    .readSchema(source)
    .catch((error: unknown) => {
      if (error instanceof CmaClient.ApiError) return undefined;
      throw error;
    });
  if (!sourceSchema)
    return {
      message: `${exported} of this project on ${createdAt}, which no longer exists or cannot be read with this API token, so its schema cannot be copied with a generated migration. Give "${target}" the dump's schema another way, for example with a migration generated from another environment that still has it, then import again. ${howToRun}`,
      suggestions: migration("<an environment with the dump's schema>"),
    };
  const changed = schemaDifferences(
    check.expected,
    schemaView(sourceSchema, trackingModelApiKey),
    source,
  ).length;
  if (changed)
    return {
      message: `${exported} of this project on ${createdAt}, but the schema of "${source}" has changed since, so a migration generated from it would not give "${target}" the dump's schema. Give "${target}" the dump's schema another way, for example with a migration generated from another environment that still has it, then import again. ${howToRun}`,
      suggestions: migration("<an environment with the dump's schema>"),
    };
  return {
    message: `${exported} of this project on ${createdAt}, and "${source}" still has the dump's schema. Copy it to "${target}" with a migration generated by the DatoCMS CLI, then import again. ${howToRun}`,
    suggestions: [
      ...migration(source),
      `datocms content:import "${dump.path}" --environment=${target}`,
    ],
  };
}
